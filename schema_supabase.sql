-- 1. Table users
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  "passwordHash" TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'sppg',
  whatsapp TEXT DEFAULT '',
  "plainPassword" TEXT DEFAULT '',
  "profilePic" TEXT DEFAULT NULL,
  "customerId" BIGINT DEFAULT NULL
);

-- 2. Table suppliers
CREATE TABLE IF NOT EXISTS public.suppliers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  code TEXT DEFAULT '',
  phone TEXT DEFAULT '',
  email TEXT DEFAULT '',
  address TEXT DEFAULT NULL,
  notes TEXT DEFAULT NULL
);

-- 3. Table barang
CREATE TABLE IF NOT EXISTS public.barang (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "supplierId" BIGINT NOT NULL,
  code TEXT NOT NULL,
  name TEXT NOT NULL,
  unit TEXT NOT NULL DEFAULT 'SAK',
  stock NUMERIC(15,2) NOT NULL DEFAULT 0,
  kategori TEXT DEFAULT 'Bahan Baku',
  notes TEXT DEFAULT NULL
);

-- 4. Table price_lists
CREATE TABLE IF NOT EXISTS public.price_lists (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "barangId" BIGINT NOT NULL,
  "hargaBeli" NUMERIC(15,2) NOT NULL DEFAULT 0,
  "hargaJual" NUMERIC(15,2) NOT NULL DEFAULT 0,
  "effectiveDate" TEXT NOT NULL,
  "effectiveDateEnd" TEXT DEFAULT ''
);

-- 5. Table customers
CREATE TABLE IF NOT EXISTS public.customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  company TEXT DEFAULT '',
  phone TEXT DEFAULT '',
  email TEXT DEFAULT '',
  address TEXT DEFAULT NULL
);

-- 6. Table po
CREATE TABLE IF NOT EXISTS public.po (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "poNumber" TEXT NOT NULL,
  "supplierId" BIGINT DEFAULT 1,
  "customerId" BIGINT DEFAULT NULL,
  "poDate" TEXT NOT NULL,
  "deliveryRequestDate" TEXT DEFAULT '',
  status TEXT NOT NULL DEFAULT 'Draft',
  "createdBy" TEXT DEFAULT '',
  "createdByDetail" TEXT DEFAULT '',
  "budgetLimit" NUMERIC(15,2) DEFAULT 0,
  "totalAmount" NUMERIC(15,2) DEFAULT 0,
  deskripsi TEXT DEFAULT NULL,
  "fileSuratJalan" TEXT DEFAULT NULL,
  "receivedDate" TEXT DEFAULT NULL,
  "receivedNotes" TEXT DEFAULT NULL,
  "receivedBy" TEXT DEFAULT NULL
);

-- 7. Table po_items
CREATE TABLE IF NOT EXISTS public.po_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "poId" BIGINT NOT NULL,
  "barangId" BIGINT NOT NULL,
  qty NUMERIC(15,2) NOT NULL DEFAULT 1,
  price NUMERIC(15,2) NOT NULL DEFAULT 0,
  total NUMERIC(15,2) NOT NULL DEFAULT 0
);

-- 8. Table bukti_pembelian
CREATE TABLE IF NOT EXISTS public.bukti_pembelian (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "buktiNumber" TEXT NOT NULL,
  "refPoId" BIGINT DEFAULT NULL,
  "poNumber" TEXT DEFAULT '',
  "supplierId" BIGINT NOT NULL,
  "receiveDate" TEXT NOT NULL,
  "totalCost" NUMERIC(15,2) NOT NULL DEFAULT 0,
  "fileBukti" TEXT DEFAULT NULL,
  notes TEXT DEFAULT NULL,
  "createdBy" TEXT DEFAULT ''
);

-- 9. Table bukti_pembelian_items
CREATE TABLE IF NOT EXISTS public.bukti_pembelian_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "buktiPembelianId" BIGINT NOT NULL,
  "barangId" BIGINT NOT NULL,
  qty NUMERIC(15,2) NOT NULL DEFAULT 1,
  "unitCost" NUMERIC(15,2) NOT NULL DEFAULT 0
);

-- 10. Table invoice_jual
CREATE TABLE IF NOT EXISTS public.invoice_jual (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "invoiceNumber" TEXT NOT NULL,
  "refPoId" BIGINT DEFAULT NULL,
  "customerId" BIGINT NOT NULL,
  "invoiceDate" TEXT NOT NULL,
  "dueDate" TEXT DEFAULT '',
  "createdByDetail" TEXT DEFAULT '',
  discount NUMERIC(15,2) DEFAULT 0,
  "taxRate" NUMERIC(5,2) DEFAULT 2,
  subtotal NUMERIC(15,2) DEFAULT 0,
  "taxAmount" NUMERIC(15,2) DEFAULT 0,
  "grandTotal" NUMERIC(15,2) DEFAULT 0,
  hpp NUMERIC(15,2) DEFAULT 0,
  status TEXT DEFAULT 'Belum Lunas'
);

-- 11. Table invoice_jual_items
CREATE TABLE IF NOT EXISTS public.invoice_jual_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "invoiceJualId" BIGINT NOT NULL,
  "barangId" BIGINT NOT NULL,
  qty NUMERIC(15,2) NOT NULL DEFAULT 1,
  price NUMERIC(15,2) NOT NULL DEFAULT 0,
  total NUMERIC(15,2) NOT NULL DEFAULT 0,
  hpp NUMERIC(15,2) DEFAULT 0
);

-- 12. Table settings
CREATE TABLE IF NOT EXISTS public.settings (
  id TEXT PRIMARY KEY,
  "companyName" TEXT DEFAULT '',
  "companyAddress" TEXT DEFAULT NULL,
  "companyPhone" TEXT DEFAULT '',
  "companyEmail" TEXT DEFAULT '',
  "taxRate" NUMERIC(5,2) DEFAULT 2,
  "bankName" TEXT DEFAULT '',
  "bankAccount" TEXT DEFAULT '',
  "bankHolder" TEXT DEFAULT '',
  logo TEXT DEFAULT NULL
);

-- 13. Table logs
CREATE TABLE IF NOT EXISTS public.logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  timestamp TEXT NOT NULL,
  action TEXT NOT NULL,
  details TEXT DEFAULT NULL
);

-- 14. Table chat_messages
CREATE TABLE IF NOT EXISTS public.chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender TEXT NOT NULL,
  role TEXT NOT NULL,
  "channelId" TEXT NOT NULL,
  content TEXT NOT NULL,
  timestamp TEXT NOT NULL,
  "readBy" JSONB DEFAULT '[]'::jsonb
);

